/**
 * Resolves the URL for a process document.
 *
 * @param {string} fileName
 * @returns {string}
 */
export function getDocUrl(fileName) {
    if (DOC_URL_MAP[fileName]) {
        return DOC_URL_MAP[fileName];
    }

    if (
        typeof fileName === 'string' &&
        fileName.endsWith('.mp4')
    ) {
        return '#PENDING_PRIVATE_DOCUMENT_MIGRATION';
    }

    return `Procesos/${fileName}`;
}

/**
 * Resolves the URL for a provider manual.
 *
 * @param {string} fileName
 * @returns {string}
 */
export function getManualUrl(fileName) {
    return MANUAL_URL_MAP[fileName] || `Manuales/${fileName}`;
}
